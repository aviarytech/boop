import fs from 'node:fs';
import ts from 'typescript';

const refs = ['api.auth.getUserByTurnkeyId', 'api.auth.getUserByEmail', 'api.auth.upsertUser'];
for (const file of fs.readdirSync('convex').filter(f => f.endsWith('.ts')).sort()) {
  const source = ts.createSourceFile(file, fs.readFileSync(`convex/${file}`, 'utf8'), ts.ScriptTarget.Latest, true);
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const declaration of statement.declarationList.declarations) {
      if (!declaration.initializer || !ts.isCallExpression(declaration.initializer)
        || !['actorQuery','actorMutation','actorAction'].includes(declaration.initializer.expression.getText(source))
        || !ts.isObjectBindingPattern(declaration.name)) continue;
      const name = declaration.name.elements.find(element => element.propertyName?.getText(source) === 'public')?.name.getText(source);
      if (name) refs.push(`api.${file.slice(0,-3)}.${name}`);
    }
  }
}
const content = `// Generated by scripts/generate-auth-client.mjs. Function references are type checked.\nimport { api } from "../../convex/_generated/api";\nimport { getFunctionName } from "convex/server";\nexport const authenticatedOperations = new Set([\n${refs.sort().map(ref => `  ${ref},`).join('\n')}\n].map(getFunctionName));\n`;
const target = 'src/lib/authenticatedOperations.ts';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target,'utf8') !== content) throw new Error('Authenticated client registry is stale: run node scripts/generate-auth-client.mjs');
} else fs.writeFileSync(target,content);
